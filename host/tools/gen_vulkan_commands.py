#!/usr/bin/env python3
"""Generates host/src/gpu/vulkan_commands.inc from vulkan_core.h.

One line per Vulkan command:
    VK_COMMAND(ReturnType, vkName, (typed parameters), (call arguments))
    VK_RESULT_COMMAND(...) for the commands that return a VkResult
The arguments pass every parameter through, except a VkAllocationCallbacks
pointer: its callbacks would be Windows x64 code called by RADV with the
System V convention, so the call passes hostVulkanAllocator(p), which reports
a non-null allocator and returns NULL (the driver's own allocation).

The commands the host writes by hand (vulkan_abi.c) are left out.
"""
import pathlib
import re
import sys

MANUAL = {
    # Resolution through the host's own tables.
    "vkGetInstanceProcAddr", "vkGetDeviceProcAddr",
    # VK_KHR_win32_surface removed from the list the driver gets.
    "vkCreateInstance",
    # Extension lists without the extensions the host hides.
    "vkEnumerateInstanceExtensionProperties", "vkEnumerateDeviceExtensionProperties",
}

def main():
    root = pathlib.Path(__file__).resolve().parents[1]
    header = root / "third_party/vulkan/vulkan/vulkan_core.h"
    output = root / "src/gpu/vulkan_commands.inc"
    text = header.read_text(encoding="utf-8")
    version = re.search(r"#define VK_HEADER_VERSION (\d+)", text).group(1)
    pattern = re.compile(r"VKAPI_ATTR\s+(.+?)\s+VKAPI_CALL\s+(vk\w+)\s*\((.*?)\);", re.S)
    lines = []
    seen = set()
    for ret, name, params in pattern.findall(text):
        if name in seen:
            sys.exit(f"duplicate command {name}")
        seen.add(name)
        if name in MANUAL:
            continue
        params = " ".join(params.split())
        if params == "void":
            typed, args = "void", ""
        else:
            names = []
            for param in params.split(","):
                match = re.search(r"(\w+)\s*(\[[^\]]*\])?\s*$", param.strip())
                if not match:
                    sys.exit(f"cannot parse parameter '{param}' of {name}")
                arg = match.group(1)
                if "VkAllocationCallbacks" in param:
                    arg = f"hostVulkanAllocator({arg})"
                names.append(arg)
            typed, args = params, ", ".join(names)
        kind = "VK_RESULT_COMMAND" if ret.strip() == "VkResult" else "VK_COMMAND"
        lines.append(f"{kind}({' '.join(ret.split())}, {name}, ({typed}), ({args}))")
    lines.sort(key=lambda line: line.split(", ")[1])
    output.write_text(
        "// Generated by host/tools/gen_vulkan_commands.py from vulkan_core.h "
        f"(VK_HEADER_VERSION {version}); do not edit.\n"
        + "\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(lines)} commands (+{len(MANUAL)} manual), VK_HEADER_VERSION {version} -> {output}")

if __name__ == "__main__":
    main()
